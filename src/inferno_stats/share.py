"""Export stats as SVG or Markdown for sharing."""

from __future__ import annotations

from pathlib import Path

from rich.console import Console
from rich.terminal_theme import MONOKAI

from inferno_stats.analysis import compute_avg_segments, generate_commentary
from inferno_stats.display import (
    format_time,
    render_attempt_detail,
    render_history_table,
    render_stats_summary,
)
from inferno_stats.models import CharacterProfile
from inferno_stats.theme import OSRS_THEME


def export_svg(profile: CharacterProfile, output: Path, width: int = 100) -> Path:
    """Render stats to an SVG file."""
    console = Console(theme=OSRS_THEME, record=True, width=width, force_terminal=True)

    render_stats_summary(console, profile)
    render_history_table(console, profile)

    if profile.pb:
        avg_splits = compute_avg_segments(profile)
        render_attempt_detail(console, profile.pb, avg_splits)

    console.save_svg(str(output), title=f"Inferno Stats: {profile.name}", theme=MONOKAI)
    return output


def export_markdown(profile: CharacterProfile, output: Path) -> Path:
    """Export stats as GitHub-flavored Markdown."""
    valid = profile.valid_attempts
    completions = profile.completions
    total = len(valid)
    comp_count = len(completions)
    rate = f"{comp_count / total * 100:.1f}%" if total > 0 else "0%"
    pb = profile.pb

    lines: list[str] = []
    lines.append(f"# \U0001f525 Inferno Stats: {profile.name}\n")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Total Attempts | {total} |")
    lines.append(f"| Completions | {comp_count} |")
    lines.append(f"| Completion Rate | {rate} |")
    lines.append(f"| Best Wave | {profile.best_wave}/69 |")
    if pb and pb.success:
        lines.append(f"| PB Time | {format_time(pb.effective_duration_seconds)} |")
    lines.append("")

    # Attempt history
    lines.append("## Attempt History\n")
    lines.append("| # | Date | Wave | Duration | Status |")
    lines.append("|---|------|------|----------|--------|")
    for a in valid:
        status = "\u2714 Cape" if a.success else f"\u2718 W{a.death_wave}"
        dur = format_time(a.effective_duration_seconds)
        lines.append(
            f"| {a.number} | {a.timestamp.strftime('%Y-%m-%d')} | {a.death_wave} | {dur} | {status} |"
        )
    lines.append("")

    # Commentary
    commentary = generate_commentary(profile)
    if commentary:
        lines.append("## Insights\n")
        for line in commentary:
            lines.append(f"- {line}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by [inferno-stats](https://github.com/masonmackey/inferno-stats)*")

    output.write_text("\n".join(lines), encoding="utf-8")
    return output
